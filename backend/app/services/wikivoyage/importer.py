"""Imports the Wikivoyage snapshot (SPEC §21).

A listing that describes a place or area we already have — a tourism place of the same name or
a similarly named one of a compatible category within 80 m, or a similarly named area around it —
never becomes a duplicate: it fills what is missing there
(a description only where it is empty or was generated by an import, opening hours, an address)
and is linked to it, so the photo job finds it. Any other well-described listing inside the
service area becomes a `preliminary` place of the system author «Викигид». Idempotent by
`external_id = wikivoyage:<listing>`; places the community hid or a moderator edited are kept.
"""

import logging
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime

from pydantic import ValidationError
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import joinedload

from app.domain import attributes as attribute_rules
from app.domain import content_check, free_text, geo, levels, trust
from app.domain.enums import PUBLIC_STATUSES, ExternalSourceId, Layer, PlaceStatus
from app.domain.geo import BBox
from app.domain.geometry import TerritoryIndex
from app.models import Area, Category, Place, User
from app.schemas.place import PlaceInput
from app.services import areas, enrichment, places
from app.services.imports import record_run, system_author
from app.services.interests import tagging as interest_tagging
from app.services.places import ExternalRef
from app.services.wikivoyage import normaliser
from app.services.wikivoyage.normaliser import MIN_DESCRIPTION_LENGTH, ListingDraft, Role
from app.services.wikivoyage.parser import Listing

logger = logging.getLogger(__name__)

SOURCE = ExternalSourceId.WIKIVOYAGE
CREDIT_LABEL = "Викигид"


@dataclass(slots=True)
class WikivoyageReport:
    places_created: int = 0
    places_updated: int = 0
    linked_to_places: int = 0
    linked_to_areas: int = 0
    descriptions_added: int = 0
    details_added: int = 0
    unmatched: int = 0
    """Listings that may only enrich, with nothing to enrich."""
    invalid: int = 0
    kept_local_edits: int = 0
    kept_closed: int = 0

    def summary(self) -> dict[str, int]:
        return {
            "places_created": self.places_created,
            "places_updated": self.places_updated,
            "linked_to_places": self.linked_to_places,
            "linked_to_areas": self.linked_to_areas,
            "descriptions_added": self.descriptions_added,
            "details_added": self.details_added,
            "unmatched": self.unmatched,
            "invalid": self.invalid,
            "kept_local_edits": self.kept_local_edits,
            "kept_closed": self.kept_closed,
        }


def _credit(draft: ListingDraft) -> enrichment.Credit:
    return enrichment.Credit(CREDIT_LABEL, free_text.TEXT_LICENSE, draft.url)


class _Candidates:
    """What a listing may describe instead of becoming a place: tourism places of the community
    and of OpenStreetMap, and areas."""

    def __init__(self, tourism: Sequence[Place], all_areas: Sequence[Area]) -> None:
        self._places = tourism
        self._areas = {area.id: area for area in all_areas}
        self._index = TerritoryIndex((area.id, area.geometry, area.area_m2) for area in all_areas)

    def place_for(self, draft: ListingDraft) -> Place | None:
        """The place the listing describes: by its very name first, then the nearest similar one."""
        found = []
        for place in self._places:
            distance = geo.haversine_m(draft.lat, draft.lng, place.lat, place.lng)
            rank = normaliser.place_match(draft, place.title, place.category.slug, distance)
            if rank is not None:
                found.append((rank, distance, place.id, place))
        return min(found)[3] if found else None

    def area_for(self, draft: ListingDraft) -> Area | None:
        """The smallest similarly named area the listing lies in or next to."""
        inside = set(self._index.containing(draft.lat, draft.lng))
        found = [
            area
            for area in self._areas.values()
            if normaliser.describes_area(
                draft,
                area.title,
                area.id in inside,
                geo.haversine_m(draft.lat, draft.lng, area.lat, area.lng),
                area.radius_m,
            )
        ]
        return min(found, key=lambda area: (area.area_m2, area.id)) if found else None

    def area_at(self, lat: float, lng: float) -> Area | None:
        area_id = self._index.smallest_containing(lat, lng)
        return self._areas.get(area_id) if area_id is not None else None


def _payload(draft: ListingDraft, category: Category | None) -> PlaceInput | None:
    if category is None:
        return None
    try:
        return PlaceInput(
            layer=category.layer,
            category_id=category.id,
            title=draft.title,
            description=draft.description,
            lat=draft.lat,
            lng=draft.lng,
            address=draft.address,
        )
    except ValidationError:
        return None


def _attributes(draft: ListingDraft, category: Category) -> dict[str, attribute_rules.AttributeValue]:
    try:
        return attribute_rules.coerce_attributes(category.fields, draft.attributes)
    except attribute_rules.InvalidAttributeError:
        return {}


def _fill_details(place: Place, draft: ListingDraft, now: datetime) -> bool:
    """Opening hours and the address where the place has none; never changes what is there."""
    missing = {
        key: value for key, value in _attributes(draft, place.category).items() if key not in place.attributes
    }
    changed = bool(missing)
    if missing:
        place.attributes = {**place.attributes, **missing}
    if not place.address and draft.address:
        place.address = draft.address
        changed = True
    if changed:
        place.search_text = places.build_search_text(
            place.title, place.description, place.address, place.tags
        )
        place.updated_at = now
    return changed


async def _merge(
    session: AsyncSession,
    draft: ListingDraft,
    place: Place | None,
    area: Area | None,
    report: WikivoyageReport,
    now: datetime,
) -> None:
    await enrichment.link(session, draft.external_id, place, area, now)
    text = draft.description if len(draft.description) >= MIN_DESCRIPTION_LENGTH else ""
    for target in (place, area):
        if target is not None and await enrichment.describe(
            session, target, text, _credit(draft), now, replaces_imports=True
        ):
            report.descriptions_added += 1
    if place is not None:
        report.linked_to_places += 1
        report.details_added += int(_fill_details(place, draft, now))
    elif area is not None:
        report.linked_to_areas += 1


def _refresh(
    place: Place, draft: ListingDraft, category: Category, payload: PlaceInput, now: datetime
) -> bool:
    """Bring an untouched Wikivoyage place in line with the guide; True when anything changed."""
    fresh = {
        "title": payload.title,
        "description": payload.description,
        "lat": payload.lat,
        "lng": payload.lng,
        "address": payload.address,
        "attributes": _attributes(draft, category),
    }
    if place.category_id == category.id and all(getattr(place, key) == value for key, value in fresh.items()):
        return False
    place.category = category
    for key, value in fresh.items():
        setattr(place, key, value)
    place.search_text = places.build_search_text(place.title, place.description, place.address, place.tags)
    place.title_key = content_check.normalize_title(place.title)
    place.updated_at = now
    return True


async def _candidates(session: AsyncSession) -> _Candidates:
    tourism = await session.scalars(
        select(Place)
        .options(joinedload(Place.category))
        .where(
            Place.layer == Layer.TOURISM,
            Place.status.in_(PUBLIC_STATUSES),
            Place.external_source.is_distinct_from(SOURCE),
        )
    )
    return _Candidates(list(tourism), list(await session.scalars(select(Area))))


async def apply_snapshot(
    session: AsyncSession, listings: Sequence[Listing], bbox: BBox, now: datetime
) -> WikivoyageReport:
    """Database phase. Commits nothing itself."""
    report = WikivoyageReport()
    author: User = await system_author(session, SOURCE, now)
    categories = {category.slug: category for category in await session.scalars(select(Category))}
    own = {
        place.external_id: place
        for place in await session.scalars(
            select(Place).options(joinedload(Place.category)).where(Place.external_source == SOURCE)
        )
    }
    candidates = await _candidates(session)
    status = trust.imported_status(SOURCE, levels.author_prior(author.level, author.role))
    created: list[tuple[Place, ListingDraft]] = []
    for draft in normaliser.normalise(listings, bbox):
        category = categories.get(draft.category)
        payload = _payload(draft, category)
        if category is None or payload is None:
            report.invalid += 1
            continue
        existing = own.get(draft.external_id)
        if existing is not None:
            if existing.status in (PlaceStatus.HIDDEN, PlaceStatus.ARCHIVED):
                report.kept_closed += 1
            elif existing.locally_edited:
                report.kept_local_edits += 1
            elif _refresh(existing, draft, category, payload, now):
                report.places_updated += 1
            continue
        place, area = candidates.place_for(draft), candidates.area_for(draft)
        if place is not None or area is not None:
            await _merge(session, draft, place, area, report, now)
        elif draft.role is Role.CREATE:
            created.append(
                (
                    places.build_place(
                        author,
                        category,
                        payload,
                        attributes=_attributes(draft, category),
                        status=status,
                        now=now,
                        area=candidates.area_at(draft.lat, draft.lng),
                        external=ExternalRef(SOURCE, draft.external_id, draft.url),
                    ),
                    draft,
                )
            )
        else:
            report.unmatched += 1
    session.add_all(place for place, _ in created)
    await session.flush()
    for place, draft in created:
        places.record_creation(session, place, now)
        enrichment.record_credit(session, place, _credit(draft), now)
    report.places_created = len(created)
    await session.flush()
    await areas.refresh_all(session, now)
    return report


async def run_import(
    session: AsyncSession, listings: Sequence[Listing], bbox: BBox, now: datetime
) -> WikivoyageReport:
    report = await apply_snapshot(session, listings, bbox, now)
    await interest_tagging.tag_stale(session, now)
    record_run(session, SOURCE, report.summary(), now)
    await session.commit()
    logger.info("Wikivoyage import: %s", report.summary())
    return report
